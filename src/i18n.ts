export function formatTierLabel(tier: ModelTier, locale: Locale): string {
  if (tier === 'free') return locale === 'id' ? 'Gratis' : 'Free';
  if (tier === 'paid') return locale === 'id' ? 'Berbayar' : 'Paid';
  return locale === 'id' ? 'Tidak diketahui' : 'Unknown';
}

export function formatDateTime(iso: string, locale: Locale): string {
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return iso;
  const diffSec = Math.round((Date.now() - date.getTime()) / 1000);
  const tag = locale === 'id' ? 'id-ID' : 'en-US';
  if (diffSec >= 0 && diffSec < 86_400) {
    if (diffSec < 60) {
      return locale === 'id' ? 'Baru saja' : 'Just now';
    }
    const rtf = new Intl.RelativeTimeFormat(tag, { numeric: 'auto' });
    if (diffSec < 3600) {
      return rtf.format(-Math.floor(diffSec / 60), 'minute');
    }
    return rtf.format(-Math.floor(diffSec / 3600), 'hour');
  }
  return new Intl.DateTimeFormat(tag, {
    day: '2-digit',
    month: 'short',
    hour: '2-digit',
    minute: '2-digit',
  }).format(date);
}

export function formatCompactNumber(n: number, locale: Locale): string {
  if (!Number.isFinite(n)) return String(n);
  return new Intl.NumberFormat(locale === 'id' ? 'id-ID' : 'en-US', {
    notation: 'compact',
    maximumFractionDigits: 2,
  }).format(n);
}

